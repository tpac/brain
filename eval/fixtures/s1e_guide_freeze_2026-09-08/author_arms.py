def sha(text):
    return hashlib.sha256(text.encode()).hexdigest()


def replace(text, old, new, label, audit, count=1):
    found = text.count(old)
    if found != count:
        raise ValueError(f'{label}: expected {count} anchors, found {found}')
    audit.append({'change': label, 'matches': found,
                  'character_delta': (len(new)-len(old))*found,
                  'old_sha256': sha(old), 'new_sha256': sha(new)})
    return text.replace(old, new)


