def with_cues(text):
    out = []; fenced = False; seen = []
    for line in text.splitlines(keepends=True):
        if line.startswith('```'):
            fenced = not fenced
        out.append(line)
        if not fenced and (line.startswith('## ') or line.startswith('### ')):
            title = line.strip().split(' ', 1)[1]
            cue = CUES[title]  # Unmapped headings fail; nothing silently uncued.
            out.append('\n*Reading cue: '+cue+'*\n')
            seen.append(title)
    assert not fenced
    return ''.join(out), seen


def generate():
    outputs = {}; audits = {}; parents = {}
    for key, (filename, expected) in PARENTS.items():
        source = (PROMPTS / filename).read_text()
        assert sha(source) == expected, f'{key} parent drifted'
        parents[key] = source
        name = 'v2_revised' if key == 'v2' else 'v3'
        outputs[name], audits[name] = revised(key, source)
        outputs[name+'_titles'], heads = with_cues(outputs[name])
        audits[name+'_titles'] = {'parent': name, 'cued_headings': heads}
    outputs['strategy'] = STRATEGY
    return outputs, audits, parents


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--write', action='store_true')
    args = ap.parse_args()
    outputs, audits, parents = generate()
    sealed = HERE / 'frozen/manifest.json'
    if args.write and sealed.exists():
        raise SystemExit('This review set is sealed. Author a new set instead.')
    for name, text in outputs.items():
        path = PROMPTS / FILES[name]
        if args.write:
            path.write_text(text)
        else:
            assert path.read_text() == text, f'Authored file differs: {path}'
        print(f'{name}: {len(text):,} chars; {sha(text)}')
    if args.write:
        (HERE / 'authoring_audit.json').write_text(json.dumps(audits, indent=2)+'\n')
        for key, base in [('v2_revised', parents['v2']), ('v3', parents['v3']),
                          ('v2_revised_titles', outputs['v2_revised']), ('v3_titles', outputs['v3'])]:
            diff = ''.join(difflib.unified_diff(base.splitlines(True), outputs[key].splitlines(True),
                                              fromfile='parent', tofile=FILES[key]))
            (HERE / (key+'.diff')).write_text(diff)


if __name__ == '__main__':
    main()
